/**
 * جابه‌جایی یک سطر در یک لیست — تنها مغزِ پشتِ کشیدن و دکمه‌های ↑/↓.
 *
 * چرا جدا از کامپوننت؟ چون ترتیبِ قاب‌ها بخشی از زبان بصریِ برند است (همان شش
 * فرمِ ثابت) و باید *قابل تست* باشد بی‌آنکه ویرایشگر رندر شود. هم رهاکردنِ
 * کشیدن و هم دکمه‌ها از همین تابع رد می‌شوند تا هرگز دو رفتارِ متفاوت نداشته
 * باشیم — همان قاعدهٔ «یک حقیقت، دو مسیر».
 *
 * قاعده‌ها:
 *  ۱) همیشه آرایهٔ **تازه** برمی‌گرداند؛ ری‌اکت برای رندرِ دوباره به تغییرِ مرجع
 *     نیاز دارد و جهشِ درجا (mutation) ترتیب را عوض می‌کند ولی صفحه را نه.
 *  ۲) ایندکسِ بیرون از محدوده، اعشاری یا برابر → لیست دست‌نخورده (کپی) برمی‌گردد.
 *     مقصدِ نامعتبر نباید سطر را «گم» کند.
 *  ۳) معنایش «برداشتن از from و گذاشتن در to» است؛ یعنی جابه‌جاییِ کامل، نه swap.
 *     با swap، کشیدنِ سطرِ اول روی سطرِ ششم فقط دو سطر را عوض می‌کرد و بقیه
 *     سرجایشان می‌ماندند — چیزی که مدیر از «کشیدن تا اینجا» انتظار ندارد.
 */
export function moveItem<T>(rows: readonly T[], from: number, to: number): T[] {
  const same = [...rows];
  if (!Number.isInteger(from) || !Number.isInteger(to)) return same;
  if (from === to || from < 0 || to < 0) return same;
  if (from >= rows.length || to >= rows.length) return same;

  const next = [...rows];
  const [row] = next.splice(from, 1);
  next.splice(to, 0, row);
  return next;
}
