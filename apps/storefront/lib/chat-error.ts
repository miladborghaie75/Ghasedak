/**
 * خطای چت — تصمیم نمایشی مشترک بین ChatWidget و لایهٔ کلاینت.
 *
 * وقتی سرور پیام تمیز می‌فرستد (مثل ۵۰۳ «چت موقتاً در دسترس نیست؛ کمی بعد
 * دوباره تلاش کن.») همان متن باید در حباب دستیار نشان داده شود، نه پیام
 * عمومی. این ماژول جداشده تا با node:test قابل تست باشد.
 */

/** پیام عمومی وقتی سرور متن تمیز نفرستاده است (شبکه قطع، بدنهٔ خالی، …) */
export const CHAT_ERROR_FALLBACK = "متأسفم، خطایی رخ داد. دوباره تلاش کن.";

/**
 * متن نهایی که در حباب دستیار نمایش داده می‌شود.
 * - متن غیرخالی سرور → همان متن (مثلاً پیام ۵۰۳)
 * - متن خالی/فقط‌فاصله → پیام عمومی
 */
export function resolveAssistantError(err?: string | null): string {
  const trimmed = (err ?? "").trim();
  return trimmed ? trimmed : CHAT_ERROR_FALLBACK;
}
